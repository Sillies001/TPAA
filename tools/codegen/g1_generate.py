#!/usr/bin/env python3
"""Generate deterministic G1 CB-1.6.0 Python/OpenAPI/TypeScript candidates."""

from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import sys
import tempfile
from collections.abc import Mapping, Sequence
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parents[2]
SRC_ROOT = REPO_ROOT / "src"
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))
if str(SRC_ROOT) not in sys.path:
    sys.path.insert(0, str(SRC_ROOT))

from tools.api.openapi_snapshot import build_snapshot  # noqa: E402
from tpaa_canonical import CanonicalArtifactLoader  # noqa: E402
from tpaa_codegen import GenerationCoordinator, default_generators  # noqa: E402

BASELINE_ROOT = REPO_ROOT / "baseline" / "CB-1.6.0"
DEFAULT_OUTPUT = REPO_ROOT / "generated" / "g1-cb-1.6.0"
CORE = "CB-1.6.0"


class G1GenerationError(RuntimeError):
    """Generated G1 candidates are missing or have drifted."""


def _sha256_bytes(value: bytes) -> str:
    return hashlib.sha256(value).hexdigest()


def _sha256(path: Path) -> str:
    return _sha256_bytes(path.read_bytes())


def _load(path: Path) -> dict[str, Any]:
    value = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(value, dict):
        raise G1GenerationError(f"expected JSON object: {path}")
    return value


def _loader() -> CanonicalArtifactLoader:
    lock = BASELINE_ROOT / "BASELINE_LOCK.json"
    payload = _load(lock)
    artifacts = payload.get("artifacts")
    if not isinstance(artifacts, list):
        raise G1GenerationError("candidate BASELINE_LOCK artifacts invalid")
    return CanonicalArtifactLoader(
        BASELINE_ROOT,
        expected_core_baseline=CORE,
        trusted_lock_sha256=_sha256(lock),
        expected_controlled_artifact_count=len(artifacts),
    )


_TS_TYPES = {
    "string": "string",
    "string?": "string | null",
    "uuid-string": "string",
    "uuid-string?": "string | null",
    "integer": "number",
    "number": "number",
    "number?": "number | null",
    "boolean": "boolean",
    "decimal-string": "string",
    "decimal-string?": "string | null",
    "array[string]": "string[]",
    "object": "Readonly<Record<string, unknown>>",
    "json-union": "unknown",
}


def _typescript(dto: Mapping[str, Any]) -> bytes:
    contracts = dto.get("contracts")
    if not isinstance(contracts, Mapping):
        raise G1GenerationError("DTO contracts invalid")
    lines = [
        "// @generated by TPAA G1 codegen; DO NOT EDIT BY HAND.",
        "// Source: CB-1.6.0/CROSS_LAYER_DTO_CONTRACTS.json",
        "",
    ]
    for name in sorted(contracts):
        contract = contracts[name]
        if not isinstance(name, str) or not isinstance(contract, Mapping):
            raise G1GenerationError("invalid DTO contract")
        fields = contract.get("fields")
        if not isinstance(fields, list):
            continue
        lines.append(f"export interface {name} {{")
        for field in fields:
            if not isinstance(field, Mapping):
                raise G1GenerationError(f"invalid field in {name}")
            field_name = field.get("field")
            transport = field.get("transport_type")
            required = field.get("required")
            if not isinstance(field_name, str) or transport not in _TS_TYPES or not isinstance(required, bool):
                raise G1GenerationError(f"unsupported field in {name}: {field!r}")
            optional = "" if required else "?"
            lines.append(f"  readonly {field_name}{optional}: {_TS_TYPES[str(transport)]};")
        lines.append("}")
        lines.append("")
    return ("\n".join(lines) + "\n").encode("utf-8")


def _write_bytes(root: Path, relative: str, content: bytes) -> dict[str, Any]:
    path = root / relative
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(content)
    return {"path": relative, "sha256": _sha256_bytes(content), "bytes": len(content)}


def build(output: Path) -> dict[str, Any]:
    if output.exists():
        raise G1GenerationError(f"output already exists: {output}")
    loader = _loader()
    summary = GenerationCoordinator(loader, default_generators()).build()
    files = []
    for generated in summary.files:
        files.append(
            _write_bytes(
                output,
                generated.relative_path.as_posix(),
                generated.content,
            )
        )
    dto = loader.load("CROSS_LAYER_DTO_CONTRACTS").payload
    files.append(_write_bytes(output, "web/contracts.ts", _typescript(dto)))
    openapi = build_snapshot(loader)
    openapi["info"] = {"title": "TPAA GUI v33 G1 Candidate", "version": "1.0.0-v33"}
    openapi_bytes = (json.dumps(openapi, ensure_ascii=False, indent=2, sort_keys=True) + "\n").encode("utf-8")
    files.append(_write_bytes(output, "api/openapi-gui-v33.json", openapi_bytes))
    manifest = {
        "schema": "TPAA_G1_GENERATED_CANDIDATE_MANIFEST_V1",
        "core_baseline": CORE,
        "baseline_lock_sha256": _sha256(BASELINE_ROOT / "BASELINE_LOCK.json"),
        "files": sorted(files, key=lambda item: item["path"]),
        "release_claim": False,
    }
    manifest_bytes = (json.dumps(manifest, ensure_ascii=False, indent=2) + "\n").encode("utf-8")
    _write_bytes(output, "manifest.json", manifest_bytes)
    return manifest


def _digest(root: Path) -> str:
    digest = hashlib.sha256()
    for path in sorted(root.rglob("*"), key=lambda item: item.as_posix()):
        if path.is_file():
            digest.update(path.relative_to(root).as_posix().encode("utf-8"))
            digest.update(b"\0")
            digest.update(path.read_bytes())
            digest.update(b"\0")
    return digest.hexdigest()


def verify(output: Path) -> str:
    if not output.is_dir():
        raise G1GenerationError(f"generated candidate missing: {output}")
    with tempfile.TemporaryDirectory(prefix="tpaa-g1-codegen-") as temporary:
        first = Path(temporary) / "first"
        second = Path(temporary) / "second"
        build(first)
        build(second)
        first_digest, second_digest, actual_digest = _digest(first), _digest(second), _digest(output)
        if first_digest != second_digest:
            raise G1GenerationError("two clean candidate builds produced different hashes")
        if actual_digest != first_digest:
            raise G1GenerationError(f"generated candidate drift: expected={first_digest} actual={actual_digest}")
        return actual_digest


def _parse_args(argv: Sequence[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--check", action="store_true")
    return parser.parse_args(argv)


def main(argv: Sequence[str] | None = None) -> int:
    args = _parse_args(argv)
    output = args.output.resolve()
    try:
        if args.check:
            print(f"G1_CODEGEN_PASS digest={verify(output)}")
        else:
            if output.exists():
                resolved = output.resolve()
                expected_parent = (REPO_ROOT / "generated").resolve()
                if expected_parent not in resolved.parents:
                    raise G1GenerationError(f"refusing to replace output outside generated/: {resolved}")
                shutil.rmtree(resolved)
            manifest = build(output)
            print(f"G1_CODEGEN_WRITE files={len(manifest['files'])} output={output}")
    except (OSError, ValueError, G1GenerationError) as exc:
        print(f"G1_CODEGEN_FAIL {exc}", file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
