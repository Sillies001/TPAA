"""Authoritative W3 business roles and permissions.

Transport credentials and legacy P4/P5/P6 projection roles are intentionally
not permissions.  A deployment role is mapped to a projection role only after
authentication and authorization have succeeded.
"""

from __future__ import annotations

from enum import StrEnum


class SecurityRole(StrEnum):
    TRAINEE = "TRAINEE"
    INSTRUCTOR = "INSTRUCTOR"
    EVALUATOR = "EVALUATOR"
    TRAINING_MANAGER = "TRAINING_MANAGER"
    UNIT_ANALYST = "UNIT_ANALYST"
    MAINTENANCE_ENGINEERING = "MAINTENANCE_ENGINEERING"
    DATA_ENGINEER = "DATA_ENGINEER"
    ADMINISTRATOR = "ADMINISTRATOR"
    MODEL_REVIEWER = "MODEL_REVIEWER"


class Permission(StrEnum):
    RAW_DATA_READ = "RAW_DATA_READ"
    DERIVED_DATA_READ = "DERIVED_DATA_READ"
    SOURCE_IMPORT = "SOURCE_IMPORT"
    COMPUTE_EXECUTE = "COMPUTE_EXECUTE"
    CONFIGURATION_WRITE = "CONFIGURATION_WRITE"
    ANNOTATION_WRITE = "ANNOTATION_WRITE"
    DIRECT_IDENTITY_READ = "DIRECT_IDENTITY_READ"
    REIDENTIFY = "REIDENTIFY"
    ASSESSMENT_APPROVE = "ASSESSMENT_APPROVE"
    RECOMMENDATION_APPROVE = "RECOMMENDATION_APPROVE"
    PROFILE_RULE_PUBLISH = "PROFILE_RULE_PUBLISH"
    MODEL_RELEASE = "MODEL_RELEASE"
    PRODUCT_PUBLISH = "PRODUCT_PUBLISH"
    PUBLICATION_OVERRIDE = "PUBLICATION_OVERRIDE"
    EXPORT_DEIDENTIFIED = "EXPORT_DEIDENTIFIED"
    EXPORT_IDENTIFIED = "EXPORT_IDENTIFIED"
    WITHDRAW_RELEASE = "WITHDRAW_RELEASE"
    PLUGIN_INSTALL = "PLUGIN_INSTALL"
    PLUGIN_ENABLE = "PLUGIN_ENABLE"
    SECURITY_AUDIT_READ = "SECURITY_AUDIT_READ"
    APPROVAL_REVIEW = "APPROVAL_REVIEW"
    BREAK_GLASS = "BREAK_GLASS"


HIGH_RISK_PERMISSIONS = frozenset(
    {
        Permission.MODEL_RELEASE,
        Permission.PRODUCT_PUBLISH,
        Permission.PUBLICATION_OVERRIDE,
        Permission.PLUGIN_INSTALL,
    }
)


__all__ = ["HIGH_RISK_PERMISSIONS", "Permission", "SecurityRole"]
